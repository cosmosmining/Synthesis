#!/usr/bin/env python3
"""Aggregate several ORFS runs (FLOW_VARIANTs) into one comparison table.

  parse_experiment.py --title "E1 clock sweep" --platform sky130hd --design ibex \
    --orfs-flow /home/user/ORFS/flow --rowlabel "Clock (ns)" \
    --cols setup_ws,hold_ws,fmax,area \
    --variant clk22:22 --variant clk20:20 ... --out reports/E1.md

Each --variant is FLOW_VARIANT:row-label. Metrics from qor_lib (raw logs).
Missing values print n/a (no fabrication).
"""
import argparse, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qor_lib as q

# key -> (header, metric, formatter)   ("mW" = W->mW special)
REG = {
    "setup_ws":   ("Setup WS (ns)",  "setup_ws",   "{:+.3f}"),
    "hold_ws":    ("Hold WS (ns)",   "hold_ws",    "{:+.3f}"),
    "tns":        ("Setup TNS (ns)", "tns",        "{:+.2f}"),
    "fmax":       ("Fmax (MHz)",     "fmax",       "{:.1f}"),
    "area":       ("Area (um^2)",    "area",       "{:.0f}"),
    "util":       ("Util (%)",       "util",       "{:.1f}"),
    "power":      ("Power (mW)",     "power",      "mW"),
    "cells":      ("Cells",          "cells",      "{}"),
    "clk_buffers":("Clk bufs",       "clk_buffers","{}"),
    "overflow":   ("GR overflow",    "overflow",   "{}"),
    "peak_usage": ("Peak GR use (%)","peak_usage", "{:.1f}"),
    "gr_wl":      ("GR WL (um)",      "gr_wl",      "{}"),
    "wirelength": ("WL (um)",         "wirelength", "{}"),
    "drc":        ("DRC",            "drc",        "{}"),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--title", required=True)
    ap.add_argument("--platform", required=True)
    ap.add_argument("--design", required=True)
    ap.add_argument("--orfs-flow", required=True)
    ap.add_argument("--rowlabel", default="Variant")
    ap.add_argument("--cols", default="setup_ws,hold_ws,fmax,area,util")
    ap.add_argument("--variant", action="append", default=[], help="FLOW_VARIANT:label")
    ap.add_argument("--note", default="")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    cols = [REG[c] for c in a.cols.split(",") if c in REG]
    header = f"| {a.rowlabel} | " + " | ".join(c[0] for c in cols) + " |"
    sep = "|" + "---|" * (len(cols) + 1)
    body = []
    for spec in a.variant:
        fv, _, label = spec.partition(":")
        base = lambda kind: os.path.join(a.orfs_flow, kind, a.platform, a.design, fv)
        m = q.extract(base("logs"), base("results"), base("reports"))
        cells = []
        for _, key, fmt in cols:
            v = m.get(key)
            if fmt == "mW":
                cells.append(f"{v*1e3:.2f}" if v is not None else "n/a")
            else:
                cells.append(q.fmt(v, fmt))
        body.append(f"| {label or fv} | " + " | ".join(cells) + " |")

    lines = [f"# {a.title}", "",
             f"_Auto-generated by `scripts/parse/parse_experiment.py` from ORFS logs "
             f"({a.platform}/{a.design}). Do not edit._", "",
             header, sep, *body, ""]
    if a.note:
        lines += [a.note, ""]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(lines))
    print(f"wrote {a.out}")
    print(header)
    for b in body:
        print(b)


if __name__ == "__main__":
    sys.exit(main())
