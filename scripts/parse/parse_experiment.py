#!/usr/bin/env python3
"""Aggregate several ORFS runs (FLOW_VARIANTs) into one comparison table.

Usage:
  parse_experiment.py --title "E1 clock sweep" --platform sky130hd --design ibex \
    --orfs-flow /home/user/ORFS/flow --rowlabel "Clock (ns)" \
    --variant clk20:20.0 --variant clk13:13.0 ... --out reports/E1.md

Each --variant is FLOW_VARIANT:row-label. One row per variant; metrics from
qor_lib (raw logs). Rows with no results yet show n/a (no fabrication).
"""
import argparse, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qor_lib as q

COLS = [
    ("Setup WS (ns)", "setup_ws", "{:+.3f}"),
    ("Hold WS (ns)",  "hold_ws",  "{:+.3f}"),
    ("Fmax (MHz)",    "fmax",     "{:.1f}"),
    ("Area (um^2)",   "area",     "{:.0f}"),
    ("Util (%)",      "util",     "{:.1f}"),
    ("Power (mW)",    "power",    None),       # special: W -> mW
    ("Clk bufs",      "clk_buffers", "{}"),
    ("WL (um)",       "wirelength", "{}"),
    ("DRC",           "drc",      "{}"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--title", required=True)
    ap.add_argument("--platform", required=True)
    ap.add_argument("--design", required=True)
    ap.add_argument("--orfs-flow", required=True)
    ap.add_argument("--rowlabel", default="Variant")
    ap.add_argument("--variant", action="append", default=[],
                    help="FLOW_VARIANT:row-label")
    ap.add_argument("--note", default="")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    header = f"| {a.rowlabel} | " + " | ".join(c[0] for c in COLS) + " |"
    sep = "|" + "---|" * (len(COLS) + 1)
    body = []
    for spec in a.variant:
        fv, _, label = spec.partition(":")
        base = lambda kind: os.path.join(a.orfs_flow, kind, a.platform, a.design, fv)
        m = q.extract(base("logs"), base("results"), base("reports"))
        cells = []
        for _, key, spec_fmt in COLS:
            v = m.get(key)
            if key == "power" and v is not None:
                cells.append(f"{v*1e3:.2f}")          # W -> mW
            else:
                cells.append(q.fmt(v, spec_fmt) if spec_fmt else q.fmt(v))
        body.append(f"| {label or fv} | " + " | ".join(cells) + " |")

    lines = [
        f"# {a.title}",
        "",
        f"_Auto-generated by `scripts/parse/parse_experiment.py` from ORFS logs "
        f"({a.platform}/{a.design}). Do not edit._",
        "",
        header, sep, *body, "",
    ]
    if a.note:
        lines += [a.note, ""]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(lines))
    print(f"wrote {a.out}")
    print(header)
    for b in body:
        print(b)


if __name__ == "__main__":
    sys.exit(main())
