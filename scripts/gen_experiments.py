#!/usr/bin/env python3
"""Generate the Ibex experiment matrix as self-contained ORFS configs + SDCs.

One config per experiment point (no hand-editing, no make-var plumbing): each
run is just `make route CONFIG=config/ibex/<pt>.mk FLOW_VARIANT=<pt>`. Re-run
this script to adjust the matrix; it is the single source of truth for it.

Experiments
  E1  clock-period ladder  -> Fmax wall + critical-path migration
  E2  WritebackStage 0->1   -> pipelining PPA delta (chparam, propagates to ID/WB)
  E3  core-utilization sweep-> congestion vs timing
"""
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = os.path.join(REPO, "config", "ibex")
SDC = os.path.join(CFG, "sdc")

PLATFORM, NICK, TOP = "sky130hd", "ibex", "ibex_core"
ASPECT, MARGIN = 1, 2
# Ibex on sky130hd is timing-bound, not area-bound (130 nm cells are slow), so a
# low utilization gives the placer room to close timing — this is also the ORFS
# default and lets the clock ladder reuse the 20%/17.4 ns calibration run.
BASE_UTIL = 20
ACHIEVABLE = 19.0             # baseline period (ns) for E2/E3 (from the E1 wall)

# Anchored by calibration: 17.4 ns already shows WNS<0 post-route, so the wall is
# ~15-20 ns. Ladder brackets it (relaxed 22 -> aggressive 15).
CLOCK_LADDER = [22.0, 20.0, 19.0, 18.0, 16.0, 15.0]   # E1
UTIL_SWEEP   = [40, 60]                                # E3 (20% reuses clk19)

VERILOG = "$(sort $(wildcard ./designs/src/ibex/*.v))"
IO_PCT = 0.2


def sdc_text(period):
    return f"""# Generated by scripts/gen_experiments.py — clock period {period} ns
current_design {TOP}
set clk_name      core_clock
set clk_port_name clk_i
set clk_period    {period}
set clk_io_pct    {IO_PCT}
set clk_port [get_ports $clk_port_name]
create_clock -name $clk_name -period $clk_period $clk_port
# I/O budget: model off-chip launch/capture as a fraction of the period.
set non_clock_inputs [lsearch -inline -all -not -exact [all_inputs] $clk_port]
set_input_delay  [expr $clk_period * $clk_io_pct] -clock $clk_name $non_clock_inputs
set_output_delay [expr $clk_period * $clk_io_pct] -clock $clk_name [all_outputs]
"""


def cfg_text(sdc_path, util, top_params=None):
    extra = f'export VERILOG_TOP_PARAMS = {top_params}\n' if top_params else ""
    return f"""# Generated by scripts/gen_experiments.py — do not edit by hand.
export DESIGN_NICKNAME = {NICK}
export DESIGN_NAME     = {TOP}
export PLATFORM        = {PLATFORM}
export VERILOG_FILES   = {VERILOG}
export SDC_FILE        = {sdc_path}
export ADDER_MAP_FILE :=
export CORE_UTILIZATION  = {util}
export CORE_ASPECT_RATIO = {ASPECT}
export CORE_MARGIN       = {MARGIN}
export FASTROUTE_TCL = $(PLATFORM_DIR)/fastroute_base.tcl
export PWR_NETS_VOLTAGES = "VDD 1.8"
export GND_NETS_VOLTAGES = "VSS 0.0"
{extra}"""


def w(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)
    print("wrote", os.path.relpath(path, REPO))


def main():
    runs = []  # (flow_variant, experiment, row-label)

    # E1: clock ladder (all at BASE_UTIL)
    for p in CLOCK_LADDER:
        name = f"clk{p:g}"
        w(os.path.join(SDC, f"{name}.sdc"), sdc_text(p))
        w(os.path.join(CFG, f"{name}.mk"),
          cfg_text(os.path.join(SDC, f"{name}.sdc"), BASE_UTIL))
        runs.append((name, "E1", f"{p:g}"))

    # achievable baseline reuses the matching clock-ladder point
    ach = f"clk{ACHIEVABLE:g}"

    # E3: utilization sweep at the achievable clock
    w(os.path.join(SDC, "achievable.sdc"), sdc_text(ACHIEVABLE))
    for u in UTIL_SWEEP:
        name = f"util{u}"
        w(os.path.join(CFG, f"{name}.mk"),
          cfg_text(os.path.join(SDC, "achievable.sdc"), u))
        runs.append((name, "E3", f"{u}"))

    # E2: WritebackStage 0 (baseline = ach) vs 1 (extra pipeline stage)
    w(os.path.join(CFG, "wb1.mk"),
      cfg_text(os.path.join(SDC, "achievable.sdc"), BASE_UTIL,
               top_params="WritebackStage 1"))
    runs.append(("wb1", "E2", "WB=1 (3-stage)"))

    print("\nRun plan (NEW variants; achievable baseline =", ach + "):")
    for fv, exp, lab in runs:
        print(f"  [{exp}] make route CONFIG=config/ibex/{fv}.mk FLOW_VARIANT={fv}   # {lab}")
    print(f"\nBaseline for E2(WB=0)/E3(util={BASE_UTIL}) reuses {ach}.")


if __name__ == "__main__":
    main()
